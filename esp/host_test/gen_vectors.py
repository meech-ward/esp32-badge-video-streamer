"""Cross-language vectors from tufty/video_streamer/stream_protocol.py."""
import random
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parents[2] / "tufty" / "video_streamer"))
import stream_protocol as P


def cbytes(data):
    return "{" + ",".join("0x%02x" % b for b in data) + "}"


def generate(out_path):
    rnd = random.Random(0x5EED)
    lines = ["// Generated by gen_vectors.py; do not edit.", "#pragma once", "#include <cstdint>", "namespace vec {"]
    hello = []
    for fs, q, credits in [(0, 6, 1), (1, 4, 4), (2, 63, 2), (3, 30, 3),
                           (4, 6, 1), (0, 3, 1), (0, 64, 1), (0, 6, 0), (0, 6, 5)]:
        try:
            packed = P.pack_hello(fs, q, credits)
            hello.append("{%d,%d,%d,true,%s}" % (fs, q, credits, cbytes(packed)))
        except P.ProtocolError:
            hello.append("{%d,%d,%d,false,{}}" % (fs, q, credits))
    lines.append("struct HelloVec { unsigned fs, q, credits; bool ok; uint8_t data[8]; };")
    lines.append("inline const HelloVec kHello[] = {" + ",".join(hello) + "};")
    headers = []
    cases = [(1, 0x1234, 160, 999, 5), (2, 65535, 0, 512, 0), (2, 1, 0, 513, 0),
             (1, 70000, 641, 131072, 0xFFFFFFFF), (1, 9, 240, 131073, 1 << 33), (3, 0, 0, 0, 0)]
    for _ in range(100):
        cases.append((rnd.choice([1, 2]), rnd.randrange(1 << 17), rnd.choice([160, 240, 320, 640]),
                      rnd.randrange(140000), rnd.randrange(1 << 34)))
    for mtype, seq, width, length, age in cases:
        packed = P.pack_header(mtype, seq, width, length, age)
        try:
            fields = P.unpack_header(packed)
            ok = "true"
        except P.ProtocolError:
            fields, ok = (0,) * 5, "false"
        headers.append("{%du,%du,%du,%du,%du,%s,%s,{%s}}" %
                       (mtype, seq, width, length, age & 0xFFFFFFFF, cbytes(packed), ok,
                        ",".join("%du" % f for f in fields)))
    lines.append("struct HeaderVec { uint32_t type, seq, width, len, age; uint8_t data[16]; bool ok; uint32_t fields[5]; };")
    lines.append("inline const HeaderVec kHeader[] = {" + ",".join(headers) + "};")
    lines.append("}  // namespace vec")
    Path(out_path).write_text("\n".join(lines) + "\n")


if __name__ == "__main__":
    generate(sys.argv[1])
