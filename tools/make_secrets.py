#!/usr/bin/env python3
"""Generate one shared Wi-Fi credential pair for the ESP32 and badge.

Only the two ignored local configuration files are written. Their contents
are never printed. Existing files require an explicit --force so a missing
half cannot silently get a password different from the installed half.
"""
import argparse
import os
from pathlib import Path
from random import SystemRandom
import string
import sys
import tempfile

ROOT = Path(__file__).resolve().parent.parent
SSID = "tufty-video"
TARGETS = {
    "esp": ROOT / "esp/main/wifi_secrets.h",
    "tufty": ROOT / "tufty/video_streamer/wifi_config.py",
}


def main(argv=None):
    parser = argparse.ArgumentParser(description=__doc__.split("\n")[0])
    parser.add_argument("--force", action="store_true", help="replace both local configurations with a new pair")
    args = parser.parse_args(argv)
    existing = [p for p in TARGETS.values() if p.exists() or p.is_symlink()]
    if existing and not args.force:
        print("credentials already exist; use --force to regenerate both files", file=sys.stderr)
        return 1
    for path in TARGETS.values():
        if path.is_symlink() or (path.exists() and not path.is_file()):
            print("refusing non-regular credential target: %s" % path, file=sys.stderr)
            return 1
    alphabet = string.ascii_letters + string.digits
    # SystemRandom uses the OS cryptographic random source.
    choose = SystemRandom().choice
    password = "".join(choose(alphabet) for _ in range(20))
    contents = {
        "esp": ("// Generated by tools/make_secrets.py. Do not commit.\n#pragma once\n"
                '#define STREAM_AP_SSID "%s"\n#define STREAM_AP_PASSWORD "%s"\n' % (SSID, password)),
        "tufty": ('# Generated by tools/make_secrets.py. Do not commit.\n'
                  'SSID = "%s"\nPASSWORD = "%s"\n' % (SSID, password)),
    }
    staged = []
    try:
        # Stage both complete files first; a failed preparation never replaces
        # either existing configuration. mkstemp creates private mode-0600 files.
        for name, path in TARGETS.items():
            path.parent.mkdir(parents=True, exist_ok=True)
            fd, temp_name = tempfile.mkstemp(prefix=".wifi-secrets-", dir=path.parent)
            temp_path = Path(temp_name)
            staged.append((temp_path, path))
            with os.fdopen(fd, "w") as f:
                f.write(contents[name])
                f.flush()
                os.fsync(f.fileno())
        for temp_path, path in staged:
            # Recheck before changing either file to catch a concurrent setup.
            if not args.force and (path.exists() or path.is_symlink()):
                raise FileExistsError("credential target appeared during generation")
        for temp_path, path in staged:
            os.replace(temp_path, path)
    except OSError as e:
        print("could not write credentials: %s; rerun with --force to regenerate both" % e, file=sys.stderr)
        return 1
    finally:
        for temp_path, _ in staged:
            temp_path.unlink(missing_ok=True)
    print("wrote esp/main/wifi_secrets.h and tufty/video_streamer/wifi_config.py (private local files)")
    return 0


if __name__ == "__main__":
    sys.exit(main())
